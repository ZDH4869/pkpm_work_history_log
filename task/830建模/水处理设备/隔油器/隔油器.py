from pyp3d import *
import math


class 隔油器(Component):
    def __init__(self):
        Component.__init__(self)
        # ============================================================
        # 基本参数组（用户可查看和修改）
        # ============================================================
        self['设备名称'] = Attr('一体式隔油器', obvious=True, group='基本参数')
        self['设备型号'] = Attr('KOS-C', obvious=True, group='基本参数')
        self['水管直径'] = Attr(70.0, obvious=True, group='基本参数')
        self['设备长度'] = Attr(2815.0, obvious=True, group='基本参数')
        self['设备宽度'] = Attr(2000.0, obvious=True, group='基本参数')
        self['设备高度'] = Attr(2270.0, obvious=True, group='基本参数')

        # ============================================================
        # 其他参数组（只读显示，供驱动点引用）
        # ============================================================
        self['主油箱宽'] = Attr(1500.0, obvious=True, readonly=True, group='其他参数')
        self['主油箱高'] = Attr(1770.0, obvious=True, readonly=True, group='其他参数')
        self['主油箱长'] = Attr(1500.0, obvious=True, readonly=True, group='其他参数')
        self['副油箱宽'] = Attr(1800.0, obvious=True, readonly=True, group='其他参数')
        self['副油箱高'] = Attr(2270.0, obvious=True, readonly=True, group='其他参数')
        self['副油箱长'] = Attr(800.0, obvious=True, readonly=True, group='其他参数')
        self['控制板宽'] = Attr(200.0, obvious=True, readonly=True, group='其他参数')
        self['控制板长'] = Attr(400.0, obvious=True, readonly=True, group='其他参数')
        self['控制板高'] = Attr(400.0, obvious=True, readonly=True, group='其他参数')
        self['圆柱22轴线终点X'] = Attr(-480.0, obvious=True, readonly=True, group='其他参数')
        self['圆柱22轴线终点Y'] = Attr(-750.0, obvious=True, readonly=True, group='其他参数')
        self['圆柱22轴线终点Z'] = Attr(885.0, obvious=True, readonly=True, group='其他参数')
        self['电箱截面X'] = Attr(-210.0, obvious=True, readonly=True, group='其他参数')
        self['左侧电箱Y向终点'] = Attr(-465.0, obvious=True, readonly=True, group='其他参数')
        self['右侧电箱Y向终点'] = Attr(-1265.0, obvious=True, readonly=True, group='其他参数')
        self['电箱截面Z'] = Attr(565.0, obvious=True, readonly=True, group='其他参数')
        self['控制板形心X'] = Attr(1900.0, obvious=True, readonly=True, group='其他参数')
        self['控制板形心Y'] = Attr(-1900.0, obvious=True, readonly=True, group='其他参数')
        self['控制板形心Z'] = Attr(2270.0, obvious=True, readonly=True, group='其他参数')

        self['隔油器'] = Attr(None, show=True)

        # ============================================================
        # 特征点（驱动点）
        # ============================================================
        # 1. 圆柱体22轴线拉伸终点
        self.setDrivenFeaturePoint('圆柱22轴线终点', SnapMode.GeometricCenter,
            '[定位点X] + [圆柱22轴线终点X]',
            '[定位点Y] + [圆柱22轴线终点Y]',
            '[定位点Z] + [圆柱22轴线终点Z]')

        # 2. 左侧油泵电箱截面沿Y轴负向的拉伸终点
        self.setDrivenFeaturePoint('左侧电箱Y向终点', SnapMode.GeometricCenter,
            '[定位点X] + [电箱截面X]',
            '[定位点Y] + [左侧电箱Y向终点]',
            '[定位点Z] + [电箱截面Z]')

        # 3. 右侧油泵电箱截面沿Y轴负向的拉伸终点（旋转后实际远端）
        self.setDrivenFeaturePoint('右侧电箱Y向终点', SnapMode.GeometricCenter,
            '[定位点X] + [电箱截面X]',
            '[定位点Y] + [右侧电箱Y向终点]',
            '[定位点Z] + [电箱截面Z]')

        # 4. 油箱控制板截面形心的拉伸起点
        self.setDrivenFeaturePoint('控制板形心拉伸起点', SnapMode.GeometricCenter,
            '[定位点X] + [控制板形心X]',
            '[定位点Y] + [控制板形心Y]',
            '[定位点Z] + [控制板形心Z]')

        # 5. 控制板形心沿Y负向平移（平移=0.5*控制板宽+0.5*副油箱宽）
        self.setDrivenFeaturePoint('控制板平移点', SnapMode.GeometricCenter,
            '[定位点X] + [控制板形心X]',
            '[定位点Y] + [控制板形心Y] + [控制板宽]*0.5 + [副油箱宽]*0.5',
            '[定位点Z] + [控制板形心Z]')

        self.replace()

    @export
    def replace(self):
        # ============================================================
        # 读取基本参数
        # ============================================================
        水管直径 = float(self['水管直径'])
        设备长度 = float(self['设备长度'])
        设备宽度 = float(self['设备宽度'])
        设备高度 = float(self['设备高度'])

        # ============================================================
        # 联动计算（基准值为初始设计值）
        # ============================================================
        设备长度基准 = 2780.0 + 0.5 * 水管直径   # 副油箱拉伸终点X(2510)-圆柱22轴线终点X(-270)+0.5*水管直径
        ΔL = 设备长度 - 设备长度基准
        ΔW = 设备宽度 - 2000.0
        ΔH = 设备高度 - 2270.0

        主油箱宽 = 1500.0 + ΔW
        主油箱高 = 1770.0 + ΔH      # 初始1770 = 2*圆柱22轴线终点Z(885)
        主油箱长 = 1500.0 + 0.5 * ΔL
        副油箱宽 = 主油箱宽 + 300.0
        副油箱高 = 主油箱高 + 500.0
        副油箱长 = 800.0 + 0.5 * ΔL
        控制板宽 = 200.0
        控制板长 = 0.5 * 副油箱长
        控制板高 = 副油箱高 - 主油箱高 - 100.0   # 恒为400

        ΔD = 水管直径 - 70.0
        圆柱21拉伸距离 = 300.0 + 0.5 * ΔW
        圆柱21终点Y = -100.0 - 圆柱21拉伸距离      # 初始 -400
        套管打孔直径 = 15.0 + 0.1*ΔD                   # 仅Step14套管打孔联动
        套管打孔半径 = 套管打孔直径 / 2.0

        # 整体平移：使主油箱前左下角点位于(0,0,0)（插入点）
        #   前=Y正向最大面，左=X负向最小面，下=Z负向底面
        #   前左下角 = (210, 主油箱形心Y+主油箱宽/2=350恒定, 0)
        整体平移X = -210.0
        整体平移Y = -350.0
        整体平移Z = 0.0

        # ============================================================
        # 基础参数
        # ============================================================
        底板边长 = 300.0          # 油泵底板正方形截面边长
        底板拉伸 = 20.0           # 油泵底板拉伸距离
        打孔直径 = 15.0           # 打孔圆截面直径
        打孔半径 = 打孔直径 / 2.0
        打孔偏移 = 10.0 + 0.5 * 打孔直径   # 17.5，角点向内偏移距离

        # ============================================================
        # Step 1: 油泵底板
        #   XOY面，以原点(0,0,0)为形心，300×300正方形截面，沿Z+拉伸20
        # ============================================================
        rect_section_1 = translate(-底板边长/2, -底板边长/2, 0) * Section(
            Vec2(0, 0), Vec2(底板边长, 0),
            Vec2(底板边长, 底板边长), Vec2(0, 底板边长)
        )
        底板 = Loft(
            translate(0, 0, 0) * rect_section_1,
            translate(0, 0, 底板拉伸) * rect_section_1
        )

        # ============================================================
        # Step 2: 油泵切板 + 布尔减
        #   XOY面，180(X)×300(Y)矩形截面，沿Z+拉伸10，底板-切板
        # ============================================================
        切板长 = 180.0
        切板拉伸 = 0.5 * 底板拉伸   # 10
        rect_section_2 = translate(-切板长/2, -底板边长/2, 0) * Section(
            Vec2(0, 0), Vec2(切板长, 0),
            Vec2(切板长, 底板边长), Vec2(0, 底板边长)
        )
        切板 = Loft(
            translate(0, 0, 0) * rect_section_2,
            translate(0, 0, 切板拉伸) * rect_section_2
        )
        底板 = 底板 - 切板

        # ============================================================
        # Step 3: 四个打孔圆柱体 + 布尔减
        #   四个角点向内偏移(10+0.5*打孔直径)，直径15，沿Z+拉伸20
        # ============================================================
        half = 底板边长 / 2.0   # 150
        hole_positions = [
            ( half - 打孔偏移,  half - 打孔偏移),   # (132.5, 132.5)
            (-half + 打孔偏移,  half - 打孔偏移),   # (-132.5, 132.5)
            (-half + 打孔偏移, -half + 打孔偏移),   # (-132.5, -132.5)
            ( half - 打孔偏移, -half + 打孔偏移),   # (132.5, -132.5)
        ]
        hole_section = Section(scale(打孔半径, 打孔半径) * Arc(2 * math.pi))
        for px, py in hole_positions:
            hole = Loft(
                translate(px, py, 0) * hole_section,
                translate(px, py, 底板拉伸) * hole_section
            )
            底板 = 底板 - hole

        # ============================================================
        # Step 4: 油泵底部竖支板1 & 2
        #   临时坐标系原点 = 底板截面形心拉伸终点 (0,0,20)
        #   梯形截面(YOZ面)：上底150，下底300，高度150，形心在(0,0,75)
        #   沿X±方向拉伸各6(厚度12)，竖支板2绕Z轴旋转90°
        # ============================================================
        梯形上底 = 0.5 * 底板边长     # 150
        梯形下底 = 底板边长           # 300
        梯形高度 = 0.5 * 底板边长     # 150
        竖支板厚度 = 12.0

        # 梯形截面在YOZ面，映射到XOY创建2D截面：(Z→X, Y→Y)，形心在原点
        梯形截面_2d = translate(0, 0, 0) * Section(
            Vec2(0, -梯形下底/2),
            Vec2(0, 梯形下底/2),
            Vec2(梯形高度, 梯形上底/2),
            Vec2(梯形高度, -梯形上底/2)
        )
        # 旋转到YOZ面
        梯形截面_yoz = roty(-math.pi/2) * 梯形截面_2d

        temp_origin_4 = Vec3(0, 0, 底板拉伸)   # (0, 0, 20)
        竖支板1 = Loft(
            translate(temp_origin_4) * translate(-竖支板厚度/2, 0, 0) * 梯形截面_yoz,
            translate(temp_origin_4) * translate(竖支板厚度/2, 0, 0) * 梯形截面_yoz
        )
        # 绕临时坐标系原点Z轴旋转90°复制
        竖支板2 = translate(temp_origin_4) * rotz(math.pi/2) * translate(-temp_origin_4) * 竖支板1

        # ============================================================
        # Step 5: 圆柱体5
        #   临时坐标系原点 = (0,0,20)，圆心(0,0,150)，直径150，沿Z+拉伸15
        # ============================================================
        圆柱5直径 = 0.5 * 底板边长    # 150
        圆柱5拉伸 = 15.0
        圆柱5截面 = Section(scale(圆柱5直径/2, 圆柱5直径/2) * Arc(2 * math.pi))
        圆柱5_Z底 = 底板拉伸 + 梯形高度     # 170
        圆柱5_Z顶 = 圆柱5_Z底 + 圆柱5拉伸   # 185
        圆柱5 = Loft(
            translate(0, 0, 圆柱5_Z底) * 圆柱5截面,
            translate(0, 0, 圆柱5_Z顶) * 圆柱5截面
        )

        # ============================================================
        # Step 6: 圆柱体6
        #   临时坐标系原点 = 圆柱5拉伸终点(0,0,185)，直径110，沿Z+拉伸30
        # ============================================================
        圆柱6直径 = 圆柱5直径 - 40.0    # 110
        圆柱6拉伸 = 2.0 * 圆柱5拉伸     # 30
        圆柱6截面 = Section(scale(圆柱6直径/2, 圆柱6直径/2) * Arc(2 * math.pi))
        圆柱6_Z底 = 圆柱5_Z顶           # 185
        圆柱6_Z顶 = 圆柱6_Z底 + 圆柱6拉伸  # 215
        圆柱6 = Loft(
            translate(0, 0, 圆柱6_Z底) * 圆柱6截面,
            translate(0, 0, 圆柱6_Z顶) * 圆柱6截面
        )

        # ============================================================
        # Step 7: 油泵中部竖支板1 & 2
        #   临时坐标系原点 = (0,0,185)，XOY面，130×10矩形，沿Z+拉伸30
        #   竖支板2绕Z轴旋转90°
        # ============================================================
        竖支板长 = 圆柱6直径 + 20.0    # 130
        竖支板宽 = 10.0
        rect_7 = translate(-竖支板长/2, -竖支板宽/2, 0) * Section(
            Vec2(0, 0), Vec2(竖支板长, 0),
            Vec2(竖支板长, 竖支板宽), Vec2(0, 竖支板宽)
        )
        中部竖支板1 = Loft(
            translate(0, 0, 圆柱6_Z底) * rect_7,
            translate(0, 0, 圆柱6_Z顶) * rect_7
        )
        temp_origin_7 = Vec3(0, 0, 圆柱6_Z底)   # (0, 0, 185)
        中部竖支板2 = translate(temp_origin_7) * rotz(math.pi/2) * translate(-temp_origin_7) * 中部竖支板1

        # ============================================================
        # Step 8: 圆柱体8
        #   临时坐标系原点 = 圆柱6拉伸终点(0,0,215)，直径190，沿Z+拉伸15
        # ============================================================
        圆柱8直径 = 圆柱5直径 + 40.0    # 190
        圆柱8拉伸 = 圆柱5拉伸           # 15
        圆柱8截面 = Section(scale(圆柱8直径/2, 圆柱8直径/2) * Arc(2 * math.pi))
        圆柱8_Z底 = 圆柱6_Z顶           # 215
        圆柱8_Z顶 = 圆柱8_Z底 + 圆柱8拉伸  # 230
        圆柱8 = Loft(
            translate(0, 0, 圆柱8_Z底) * 圆柱8截面,
            translate(0, 0, 圆柱8_Z顶) * 圆柱8截面
        )

        # ============================================================
        # Step 9: 半椭球油泵半椭球底帽
        #   临时坐标系原点 = 圆柱8拉伸终点(0,0,230)
        #   圆心(0,0,30)，直径260，沿Z-拉伸30，椭球渐变至终点直径190
        #   使用半椭球Loft方式：截取椭球从直径260到直径190的段落
        # ============================================================
        半椭球起点直径 = 260.0
        半椭球终点直径 = 圆柱8直径    # 190
        半椭球拉伸 = 30.0
        半椭球起点半径 = 半椭球起点直径 / 2.0   # 130
        半椭球终点半径 = 半椭球终点直径 / 2.0   # 95

        # 计算完整椭球高度：r(z) = R_max * sqrt(1 - (z/H_total)²)
        # 在z=半椭球拉伸处，r = 半椭球终点半径
        H_total = 半椭球拉伸 / math.sqrt(max(1e-6, 1.0 - (半椭球终点半径/半椭球起点半径)**2))

        半椭球Z底 = 圆柱8_Z顶                    # 230（终点，直径190）
        半椭球Z顶 = 半椭球Z底 + 半椭球拉伸        # 260（起点，直径260）

        n = 25
        sections_9 = []
        for i in range(n):
            t = 1.0 * i / (n - 1)               # t ∈ [0, 1]，从大端到小端
            z_from_top = 半椭球拉伸 * t
            z_ratio = z_from_top / H_total
            scale_xy = math.sqrt(max(0.0, 1.0 - z_ratio * z_ratio))
            r = max(半椭球起点半径 * scale_xy, 1e-3)
            sections_9.append(
                translate(0, 0, 半椭球Z顶 - z_from_top) * scale(r, r) * Section(Arc(2 * math.pi))
            )
        半椭球底帽 = Loft(*sections_9)
        半椭球底帽.smooth = True

        # ============================================================
        # Step 10: 圆柱体10
        #   临时坐标系原点 = 半椭球底帽拉伸起点(0,0,260)，直径260，沿Z+拉伸50
        # ============================================================
        圆柱10直径 = 半椭球起点直径    # 260
        圆柱10拉伸 = 50.0 + ΔD         # 50 + ΔD（水管直径等量增量联动）
        圆柱10截面 = Section(scale(圆柱10直径/2, 圆柱10直径/2) * Arc(2 * math.pi))
        圆柱10_Z底 = 半椭球Z顶                     # 260
        圆柱10_Z顶 = 圆柱10_Z底 + 圆柱10拉伸        # 310
        圆柱10 = Loft(
            translate(0, 0, 圆柱10_Z底) * 圆柱10截面,
            translate(0, 0, 圆柱10_Z顶) * 圆柱10截面
        )

        # ============================================================
        # Step 11: 镜像复制 — 半椭球顶帽 + 圆柱体11
        #   临时坐标系原点 = 圆柱10中点(0,0,285)
        #   将半椭球底帽和圆柱8沿XOY面镜像
        # ============================================================
        圆柱10中点Z = 圆柱10_Z底 + 圆柱10拉伸 / 2.0   # 285
        mirror_origin = Vec3(0, 0, 圆柱10中点Z)
        半椭球顶帽 = translate(mirror_origin) * scale(1, 1, -1) * translate(-mirror_origin) * 半椭球底帽
        圆柱11 = translate(mirror_origin) * scale(1, 1, -1) * translate(-mirror_origin) * 圆柱8

        # ============================================================
        # Step 12: 连接管出管
        #   临时坐标系原点 = 圆柱10中点(0,0,285)
        #   YOZ面，圆心原点，直径=2*30+50=110，沿X-拉伸170
        # ============================================================
        连接管直径 = 2.0 * 半椭球拉伸 + 圆柱10拉伸 + 0.5 * ΔD   # 110 + 0.5ΔD（水管直径联动）
        连接管拉伸 = 0.5 * 圆柱10直径 + 40.0         # 170
        连接管截面 = Section(scale(连接管直径/2, 连接管直径/2) * Arc(2 * math.pi))
        连接管截面_yoz = roty(-math.pi/2) * 连接管截面
        连接管出管 = Loft(
            translate(0, 0, 圆柱10中点Z) * 连接管截面_yoz,
            translate(-连接管拉伸, 0, 圆柱10中点Z) * 连接管截面_yoz
        )

        # ============================================================
        # Step 13: 连接管出管套管
        #   临时坐标系原点 = 连接管出管拉伸终点(-170,0,285)
        #   YOZ面，直径=110+50=160，沿X+拉伸10
        # ============================================================
        套管直径 = 连接管直径 + 50.0    # 160
        套管拉伸 = 10.0
        套管截面 = Section(scale(套管直径/2, 套管直径/2) * Arc(2 * math.pi))
        套管截面_yoz = roty(-math.pi/2) * 套管截面
        套管X起点 = -连接管拉伸                      # -300
        套管X终点 = 套管X起点 + 套管拉伸              # -290
        套管 = Loft(
            translate(套管X起点, 0, 圆柱10中点Z) * 套管截面_yoz,
            translate(套管X终点, 0, 圆柱10中点Z) * 套管截面_yoz
        )

        # ============================================================
        # Step 14: 连接管出管套管打孔圆柱体群 + 布尔减
        #   临时坐标系原点 = 套管拉伸终点(-160,0,285)
        #   圆心(0,0,67.5)，直径15，绕X轴旋转45°后沿X-拉伸10（向套管内部）
        #   再绕X轴旋转90°/180°/270°复制3次，共4个打孔圆柱
        # ============================================================
