        self['圆柱体15拉伸距离'] = Attr(10.0, obvious=True, readonly=True, group='其他参数')
        self['圆柱体16拉伸距离'] = Attr(45.0, obvious=True, readonly=True, group='其他参数')
        self['圆柱体17拉伸距离'] = Attr(80.0, obvious=True, readonly=True, group='其他参数')
