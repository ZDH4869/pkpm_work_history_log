from pyp3d import *
import math

class 格兰富MTH水泵(Component):
    def __init__(self):
        Component.__init__(self)

        # ========== 用户可修改参数 ==========
        self['设备名称'] = Attr('格兰富MTH水泵', obvious=True)
        self['水泵主管直径'] = Attr(50.0, obvious=True)
        self['水泵套管直径'] = Attr(100.0, obvious=True)
        self['水泵高度'] = Attr(1200.0, obvious=True)
        self['支撑板边长'] = Attr(500.0, obvious=True)

        # ========== 只读计算参数（供特征点表达式引用） ==========
        self['支撑柱拉伸距离'] = Attr(900.0, obvious=True, readonly=True)
        self['主管拉伸距离'] = Attr(350.0, obvious=True, readonly=True)
        self['主管圆心Z'] = Attr(1025.0, obvious=True, readonly=True)
        self['插线板拉伸终点X'] = Attr(-300.0, obvious=True, readonly=True)
        self['插线板形心Z'] = Attr(1350.0, obvious=True, readonly=True)

        # ========== 输出槽位 ==========
        self['水泵'] = Attr(None, show=True)

        # ========== 特征点定义 ==========
        # 1. 插入点：支撑柱底面圆心 (0,0,0)
        self.setDrivenFeaturePoint('插入点', SnapMode.GeometricCenter,
            '[定位点X]', '[定位点Y]', '[定位点Z]')

        # 2. 水泵主管拉伸终点
        self.setDrivenFeaturePoint('水泵主管拉伸终点', SnapMode.GeometricCenter,
            '[定位点X] + [主管拉伸距离]',
            '[定位点Y]',
            '[定位点Z] + [主管圆心Z]')

        # 3. 插线板矩形截面形心的拉伸终点
        self.setDrivenFeaturePoint('插线板拉伸终点', SnapMode.GeometricCenter,
            '[定位点X] + [插线板拉伸终点X]',
            '[定位点Y]',
            '[定位点Z] + [插线板形心Z]')

        self.replace()

    @export
    def replace(self):
        # ========== 读取用户参数 ==========
        水泵主管直径 = self['水泵主管直径']
        水泵套管直径 = self['水泵套管直径']
        水泵高度 = self['水泵高度']
        支撑板边长 = self['支撑板边长']

        # ========== 固定拉伸距离 ==========
        固定板拉伸距离 = 100.0
        散热箱拉伸距离 = 700.0
        顶帽拉伸距离 = 100.0

        # ========== 计算支撑柱拉伸距离（水泵高度变化时仅此项变化） ==========
        支撑柱拉伸距离 = 水泵高度 - 固定板拉伸距离 - 散热箱拉伸距离 - 顶帽拉伸距离

        # ========== 缩放比（支撑板边长变化时等比缩放其他截面尺寸） ==========
        缩放比 = 支撑板边长 / 500.0
        支撑柱直径 = 500.0 * 缩放比
        散热箱边长 = 450.0 * 缩放比
        顶帽边长 = 500.0 * 缩放比

        # ========== 关键Z坐标 ==========
        Z1 = 支撑柱拉伸距离                        # 固定板底面Z（也是支撑柱顶面Z）
        Z2 = 支撑柱拉伸距离 + 固定板拉伸距离          # 散热箱底面Z = 固定板顶面Z
        Z3 = 支撑柱拉伸距离 + 固定板拉伸距离 + 散热箱拉伸距离  # 顶帽底面Z

        # 散热箱轴线中点Z
        散热箱中点Z = Z2 + 散热箱拉伸距离 / 2.0

        # ========== 水泵主管参数 ==========
        主管半径 = 水泵主管直径 / 2.0
        主管拉伸距离 = 0.5 * 支撑板边长 + 50
        主管圆心Z = Z2 + 主管半径

        # ========== 水泵套管参数 ==========
        套管半径 = 水泵套管直径 / 2.0

        # ========== 插线板参数 ==========
        插线板高度 = 0.5 * 散热箱拉伸距离        # Z方向
        插线板宽度 = 0.6 * 散热箱边长           # Y方向
        插线板拉伸距离 = 0.6 * 散热箱边长         # X方向

        # ========== 更新只读参数（供特征点表达式使用） ==========
        self['支撑柱拉伸距离'] = 支撑柱拉伸距离
        self['主管拉伸距离'] = 主管拉伸距离
        self['主管圆心Z'] = 主管圆心Z
        self['插线板拉伸终点X'] = -插线板拉伸距离
        self['插线板形心Z'] = 散热箱中点Z

        # ========== 辅助函数：创建XOY面矩形截面（形心在原点） ==========
        def rect_section_xoy(width, height):
            """在XOY面创建矩形截面，形心在原点。
            矩形四个顶点相对于形心均匀分布：
            width为X轴方向长度，height为Y轴方向长度。"""
            return translate(-width / 2.0, -height / 2.0, 0) * Section(
                Vec2(0, 0), Vec2(width, 0), Vec2(width, height), Vec2(0, height)
            )

        # ========== 1. 支撑柱：xoy面，(0,0,0)圆心，直径500*缩放比，沿Z+拉伸 ==========
        支撑柱半径 = 支撑柱直径 / 2.0
        支撑柱 = Cone(
            Vec3(0, 0, 0),
            Vec3(0, 0, 支撑柱拉伸距离),
            支撑柱半径, 支撑柱半径
        )

        # ========== 2. 固定板：xoy面，形心(0,0,Z1)，正方形截面边长=支撑板边长，沿Z+拉伸 ==========
        固定板截面 = rect_section_xoy(支撑板边长, 支撑板边长)
        固定板 = Loft(
            translate(0, 0, Z1) * 固定板截面,
            translate(0, 0, Z2) * 固定板截面
        )

        # ========== 3. 散热箱：xoy面，形心(0,0,Z2)，正方形截面，沿Z+拉伸 ==========
        散热箱截面 = rect_section_xoy(散热箱边长, 散热箱边长)
        散热箱 = Loft(
            translate(0, 0, Z2) * 散热箱截面,
            translate(0, 0, Z3) * 散热箱截面
        )

        # ========== 4. 顶帽：xoy面，形心(0,0,Z3)，正方形截面，沿Z+拉伸 ==========
        顶帽截面 = rect_section_xoy(顶帽边长, 顶帽边长)
        顶帽 = Loft(
            translate(0, 0, Z3) * 顶帽截面,
            translate(0, 0, Z3 + 顶帽拉伸距离) * 顶帽截面
        )

        # ========== 5. 水泵主管：xoz面，(0,0,主管圆心Z)圆心，沿X+拉伸 ==========
        水泵主管 = Cone(
            Vec3(0, 0, 主管圆心Z),
            Vec3(主管拉伸距离, 0, 主管圆心Z),
            主管半径, 主管半径
        )

        # ========== 6. 水泵套管：圆环截面（内径=水泵主管直径，外径=水泵套管直径），沿X+拉伸 ==========
        套管外柱 = Cone(
            Vec3(主管拉伸距离, 0, 主管圆心Z),
            Vec3(主管拉伸距离 + 50.0, 0, 主管圆心Z),
            套管半径, 套管半径
        )
        套管内柱 = Cone(
            Vec3(主管拉伸距离, 0, 主管圆心Z),
            Vec3(主管拉伸距离 + 50.0, 0, 主管圆心Z),
            主管半径, 主管半径
        )
        水泵套管 = 套管外柱 - 套管内柱

        # ========== 7. 插线板：yoz面，散热箱中点Z为形心，沿X-拉伸 ==========
        # 截面在XOY面创建：X=高度(Z方向), Y=宽度(Y方向)
        # 绕Y轴旋转-90°使X→Z, Y→Y（截面从XOY面转到YOZ面）
        插线板截面_xoy = rect_section_xoy(插线板高度, 插线板宽度)
        插线板截面_yoz = roty(-math.pi / 2.0) * 插线板截面_xoy
        插线板 = Loft(
            translate(0, 0, 散热箱中点Z) * 插线板截面_yoz,
            translate(-插线板拉伸距离, 0, 散热箱中点Z) * 插线板截面_yoz
        )

        # ========== 8. 散热片阵列：散热箱体外侧三个面的线性阵列 ==========
        散热片厚度 = 10.0       # 沿阵列方向的厚度
        散热片深度 = 20.0       # 沿外伸方向的深度
        散热片高度 = 0.85 * 散热箱拉伸距离  # 散热片高度
        散热片间距 = 50.0       # 阵列间距（中心到中心）

        # 散热片截面A：用于X负向面，深度(X方向)=20，厚度(Y方向)=10
        散热片截面_X面 = rect_section_xoy(散热片深度, 散热片厚度)

        # 散热片截面B：用于Y负向面和Y正向面，厚度(X方向)=10，深度(Y方向)=20
        散热片截面_Y面 = rect_section_xoy(散热片厚度, 散热片深度)

        # 计算每个面的散热片数量
        散热片数量 = int((散热箱边长 - 散热片厚度) / 散热片间距) + 1

        half_side = 散热箱边长 / 2.0
        # 居中放置：阵列整体形心与阵列面形心重合
        start_pos = -(散热片数量 - 1) * 散热片间距 / 2.0

        # 散热片Z方向范围（居中于散热箱中点）
        散热片Z底 = 散热箱中点Z - 散热片高度 / 2.0
        散热片Z顶 = 散热箱中点Z + 散热片高度 / 2.0

        # 创建单个散热片（截面在XOY面，形心在(cx,cy)，沿Z拉伸）
        def 创建散热片(section, cx, cy):
            return Loft(
                translate(cx, cy, 散热片Z底) * section,
                translate(cx, cy, 散热片Z顶) * section
            )

        散热片列表 = []

        # 面A：Y负向面（沿Y负向视角查看的正面），散热片贴在外侧，阵列沿X方向
        fin_cy = -half_side - 散热片深度 / 2.0
        for i in range(散热片数量):
            fin_cx = start_pos + i * 散热片间距
            散热片列表.append(创建散热片(散热片截面_Y面, fin_cx, fin_cy))

        # 面B：Y正向面（沿Y负向视角查看的背面），散热片贴在外侧，阵列沿X方向
        fin_cy = half_side + 散热片深度 / 2.0
        for i in range(散热片数量):
            fin_cx = start_pos + i * 散热片间距
            散热片列表.append(创建散热片(散热片截面_Y面, fin_cx, fin_cy))

        # 面C：X正向面（沿X负向视角查看的正面 = 沿X正向视角查看的背面，左视图面），散热片贴在外侧，阵列沿Y方向
        fin_cx = half_side + 散热片深度 / 2.0
        for i in range(散热片数量):
            fin_cy = start_pos + i * 散热片间距
            散热片列表.append(创建散热片(散热片截面_X面, fin_cx, fin_cy))

        # 合并所有散热片
        散热片阵列 = combine(*散热片列表)

        # ========== 组合所有部件 ==========
        self['水泵'] = 支撑柱 + 固定板 + 散热箱 + 顶帽 + 水泵主管 + 水泵套管 + 插线板 + 散热片阵列


if __name__ == "__main__":
    FinalGeometry = 格兰富MTH水泵()
    place(FinalGeometry)