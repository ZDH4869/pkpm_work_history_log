from pyp3d import *
import math


class QW型潜污泵(Component):
    def __init__(self):
        Component.__init__(self)

        # ========== 基本参数 ==========
        self['设备名称'] = Attr('QW型潜污泵', obvious=True, group='基本参数')
        self['设备型号'] = Attr('100QW100-7-4', obvious=True, group='基本参数')
        self['出水管直径'] = Attr(100.0, obvious=True, group='基本参数')
        self['设备长度'] = Attr(625.0, obvious=True, group='基本参数')
        self['设备宽度'] = Attr(360.0, obvious=True, group='基本参数')
        self['设备高度'] = Attr(750.0, obvious=True, group='基本参数')

        # ========== 其他参数（驱动点引用） ==========
        self['圆形线扫掠路径直径'] = Attr(240.0, obvious=True, readonly=True, group='其他参数')
        self['圆环扫掠截面直径'] = Attr(120.0, obvious=True, readonly=True, group='其他参数')
        self['出水管扫掠路径直径'] = Attr(200.0, obvious=True, readonly=True, group='其他参数')

        # 驱动点辅助参数
        self['盖顶圆台1底直径'] = Attr(180.0, obvious=True, readonly=True, group='其他参数')
        self['盖顶圆台1底圆心Z'] = Attr(635.0, obvious=True, readonly=True, group='其他参数')
        self['出水管弯头终点X'] = Attr(-395.0, obvious=True, readonly=True, group='其他参数')
        self['出水管弯头终点Z'] = Attr(285.0, obvious=True, readonly=True, group='其他参数')

        # 内部补偿跟踪参数（隐藏，用于检测用户是否修改了设备长度/高度）
        self['_长度补偿'] = Attr(100.0)
        self['_上次设备长度'] = Attr(625.0)
        self['_高度补偿'] = Attr(120.0)
        self['_上次设备高度'] = Attr(750.0)

        # ========== 输出槽位 ==========
        self['QW型潜污泵'] = Attr(None, show=True)

        # ========== 特征点定义 ==========
        # 1. 插入点 (0, 0, 0)
        self.setDrivenFeaturePoint('插入点', SnapMode.GeometricCenter,
            '[定位点X]', '[定位点Y]', '[定位点Z]')

        # 2. 出水管圆环的顶部截面圆心（出水管扫掠路径的-pi终点位置）
        self.setDrivenFeaturePoint('出水管弯头终点', SnapMode.GeometricCenter,
            '[定位点X] + [出水管弯头终点X]',
            '[定位点Y]',
            '[定位点Z] + [出水管弯头终点Z]')

        # 3. 盖顶圆台1底部圆形截面圆心沿X负向平移
        self.setDrivenFeaturePoint('盖顶平移点', SnapMode.GeometricCenter,
            '[定位点X] - (0.5 * [盖顶圆台1底直径] + 10)',
            '[定位点Y]',
            '[定位点Z] + [盖顶圆台1底圆心Z]')

        self.replace()

    @export
    def replace(self):
        # ========== 读取用户参数 ==========
        出水管直径 = self['出水管直径']
        设备长度 = self['设备长度']
        设备宽度 = self['设备宽度']
        设备高度 = self['设备高度']
        出水管扫掠路径直径 = self['出水管扫掠路径直径']

        # ========== 基础常量（初始默认值） ==========
        设备宽度_base = 360.0
        圆形线扫掠路径直径_base = 240.0
        圆环扫掠截面直径_base = 120.0

        # ========== 宽度缩放比 ==========
        宽度缩放比 = 设备宽度 / 设备宽度_base

        # ========== 更新圆形线扫掠路径直径（随设备宽度变化） ==========
        圆形线扫掠路径直径 = 圆形线扫掠路径直径_base * 宽度缩放比
        self['圆形线扫掠路径直径'] = 圆形线扫掠路径直径

        # ========== 更新圆环扫掠截面直径（随设备宽度变化） ==========
        圆环扫掠截面直径 = 圆环扫掠截面直径_base * 宽度缩放比
        self['圆环扫掠截面直径'] = 圆环扫掠截面直径

        # ========== 长度补偿：基于自然设备长度（不含补偿的理论值）动态计算 ==========
        # 自然设备长度 = 0.5*出水管直径 + 0.5*出水管扫掠路径直径 + 圆柱体15拉伸距离 + 圆形线扫掠路径直径 + 圆环扫掠截面直径
        自然设备长度 = 0.5 * 出水管直径 + 0.5 * 出水管扫掠路径直径 + 15.0 + 圆形线扫掠路径直径 + 圆环扫掠截面直径

        # 检测用户是否修改了设备长度：当前值 != 上次回写值
        if abs(设备长度 - self['_上次设备长度']) > 0.001:
            self['_长度补偿'] = 设备长度 - 自然设备长度
            self['_上次设备长度'] = 设备长度
        长度补偿 = self['_长度补偿']

        # ========== 计算各部件直径（随宽度缩放比变化，固定偏移量不缩放） ==========
        底板直径 = 260.0 * 宽度缩放比
        支撑圆台1底直径 = 底板直径 - 20.0
        支撑圆台1顶直径 = 180.0 * 宽度缩放比
        支撑圆台2底直径 = 支撑圆台1顶直径
        支撑圆台2顶直径 = 底板直径 - 30.0
        圆柱体4直径 = 支撑圆台2顶直径 - 20.0
        圆柱体6直径 = 圆形线扫掠路径直径
        圆柱体8直径 = 圆柱体6直径 - 20.0
        圆柱体10直径 = 圆柱体6直径 - 20.0
        盖顶圆台1底直径 = 圆柱体6直径 - 60.0
        盖顶圆台1顶直径 = 120.0 * 宽度缩放比

        # ========== 固定拉伸距离 ==========
        底板拉伸距离 = 15.0
        支撑圆台1拉伸距离 = 85.0
        支撑圆台2拉伸距离 = 25.0
        圆柱体4拉伸距离 = 20.0
        圆柱体6拉伸距离 = 40.0
        圆柱体8拉伸距离 = 80.0
        盖顶圆台1拉伸距离 = 85.0
        圆柱体15拉伸距离 = 15.0

        # ========== 计算关键Z坐标 ==========
        Z0 = 0.0                                                       # 底板底面
        Z1 = Z0 + 底板拉伸距离                                          # 底板顶面 = 支撑圆台1底面
        Z2 = Z1 + 支撑圆台1拉伸距离                                      # 支撑圆台1顶面 = 支撑圆台2底面
        Z3 = Z2 + 支撑圆台2拉伸距离                                      # 支撑圆台2顶面 = 圆柱体4底面
        Z4 = Z3 + 圆柱体4拉伸距离                                       # 圆柱体4顶面

        # 圆环管圆心Z（在圆台体支撑圆台2轴线终点基础上偏移，减50使圆环管下移）
        圆环管圆心Z = Z3 + (圆环扫掠截面直径 - 0.5 * 圆柱体4拉伸距离) - 50.0

        Z6 = 圆环管圆心Z + 50.0                                       # 圆柱体6底面（补偿50，保持原高度不变）
        Z7 = Z6 + 圆柱体6拉伸距离                                       # 圆柱体6顶面

        # ========== 高度补偿：基于自然设备高度动态计算 ==========
        # 自然设备高度 = Z6 + 395（不含高度补偿时的理论值）
        自然设备高度 = Z6 + 395.0

        # 检测用户是否修改了设备高度：当前值 != 上次回写值
        if abs(设备高度 - self['_上次设备高度']) > 0.001:
            self['_高度补偿'] = 设备高度 - 自然设备高度
            self['_上次设备高度'] = 设备高度
        高度补偿 = self['_高度补偿']

        Z8 = Z7                                                         # 圆柱体8底面
        Z9 = Z8 + 圆柱体8拉伸距离                                       # 圆柱体8顶面

        # 圆柱体9：圆柱体6和散热片沿XOY面镜像（镜像面Z = 圆柱体8拉伸中点）
        圆柱体8拉伸中点Z = Z8 + 圆柱体8拉伸距离 / 2.0
        Z6_mirror = 圆柱体8拉伸中点Z + (圆柱体8拉伸中点Z - Z7)           # 圆柱体9底面
        Z7_mirror = 圆柱体8拉伸中点Z + (圆柱体8拉伸中点Z - Z6)           # 圆柱体9顶面

        # 圆柱体10拉伸距离（含高度补偿）
        圆柱体10拉伸距离 = 圆柱体8拉伸距离 + 高度补偿
        Z10 = Z7_mirror                                                  # 圆柱体10底面
        Z11 = Z10 + 圆柱体10拉伸距离                                     # 圆柱体10顶面

        # 圆柱体11：圆柱体9沿XOY面镜像（镜像面Z = 圆柱体10拉伸中点）
        圆柱体10拉伸中点Z = Z10 + 圆柱体10拉伸距离 / 2.0
        Z9_mirror = 圆柱体10拉伸中点Z + (圆柱体10拉伸中点Z - Z7_mirror)  # 圆柱体11底面
        Z10_mirror = 圆柱体10拉伸中点Z + (圆柱体10拉伸中点Z - Z6_mirror) # 圆柱体11顶面

        # 盖顶圆台1（以圆柱体11轴线拉伸终点即Z10_mirror为临时坐标系原点）
        Z12 = Z10_mirror                                                  # 盖顶圆台1底面（圆柱体11顶面）
        Z13 = Z12 + 盖顶圆台1拉伸距离                                    # 盖顶圆台1顶面

        # 圆柱体14拉伸距离（含长度补偿）
        圆柱体14拉伸距离 = 0.5 * 圆形线扫掠路径直径 + 0.5 * 圆环扫掠截面直径 + 长度补偿

        # 出水管弯头起点
        出水管弯头起点X = -(圆柱体14拉伸距离 + 圆柱体15拉伸距离)
        出水管弯头起点Z = 圆环管圆心Z

        # ========== 更新只读参数（供驱动点表达式使用） ==========
        self['盖顶圆台1底直径'] = 盖顶圆台1底直径
        self['盖顶圆台1底圆心Z'] = Z12
        self['出水管弯头终点X'] = 出水管弯头起点X - 出水管扫掠路径直径 / 2.0
        self['出水管弯头终点Z'] = 出水管弯头起点Z + 出水管扫掠路径直径 / 2.0

        # ========== 回写设备长度和设备高度（宽度联动后实际值可能变化） ==========
        # 设备长度 = 自然设备长度 + 长度补偿
        设备长度 = 自然设备长度 + 长度补偿
        self['设备长度'] = 设备长度
        self['_上次设备长度'] = 设备长度
        # 设备高度 = 自然设备高度 + 高度补偿
        设备高度 = 自然设备高度 + 高度补偿
        self['设备高度'] = 设备高度
        self['_上次设备高度'] = 设备高度

        # ========== 计算半径 ==========
        底板半径 = 底板直径 / 2.0
        支撑圆台1底半径 = 支撑圆台1底直径 / 2.0
        支撑圆台1顶半径 = 支撑圆台1顶直径 / 2.0
        支撑圆台2底半径 = 支撑圆台2底直径 / 2.0
        支撑圆台2顶半径 = 支撑圆台2顶直径 / 2.0
        圆柱体4半径 = 圆柱体4直径 / 2.0
        圆柱体6半径 = 圆柱体6直径 / 2.0
        圆柱体8半径 = 圆柱体8直径 / 2.0
        圆柱体10半径 = 圆柱体10直径 / 2.0
        盖顶圆台1底半径 = 盖顶圆台1底直径 / 2.0
        盖顶圆台1顶半径 = 盖顶圆台1顶直径 / 2.0
        圆柱体14直径 = 圆环扫掠截面直径 - 20.0
        圆柱体14半径 = 圆柱体14直径 / 2.0
        圆柱体15直径 = 圆柱体14直径 + 100.0
        圆柱体15半径 = 圆柱体15直径 / 2.0
        出水管半径 = 出水管直径 / 2.0
        出水管扫掠路径半径 = 出水管扫掠路径直径 / 2.0
        圆环管路径半径 = 圆形线扫掠路径直径 / 2.0
        圆环管截面半径 = 圆环扫掠截面直径 / 2.0

        # ======================================================================
        # 步骤1：底板 — XOY面，(0,0,0)圆心，直径260*缩放比，沿Z+拉伸15
        # ======================================================================
        底板 = Cone(
            Vec3(0, 0, Z0),
            Vec3(0, 0, Z1),
            底板半径, 底板半径
        )

        # ======================================================================
        # 步骤2：支撑圆台1 — 临时坐标系原点(0,0,Z1)，底直径=底板直径-20，顶直径=180*缩放比，沿Z+拉伸85
        # ======================================================================
        支撑圆台1 = Cone(
            Vec3(0, 0, Z1),
            Vec3(0, 0, Z2),
            支撑圆台1底半径, 支撑圆台1顶半径
        )

        # ======================================================================
        # 步骤3：支撑圆台2 — 临时坐标系原点(0,0,Z2)，底直径=支撑圆台1顶直径，顶直径=底板直径-30，沿Z+拉伸25
        # ======================================================================
        支撑圆台2 = Cone(
            Vec3(0, 0, Z2),
            Vec3(0, 0, Z3),
            支撑圆台2底半径, 支撑圆台2顶半径
        )

        # ======================================================================
        # 步骤4：圆柱体4 — 临时坐标系原点(0,0,Z3)，直径=支撑圆台2顶直径-20，沿Z+拉伸20
        # ======================================================================
        圆柱体4 = Cone(
            Vec3(0, 0, Z3),
            Vec3(0, 0, Z4),
            圆柱体4半径, 圆柱体4半径
        )

        # ======================================================================
        # 步骤5：圆环管 — 临时坐标系原点(0,0,Z3)，圆心(0,0,圆环管圆心Z)，XOY面路径直径=圆形线扫掠路径直径，
        #         XOZ面截面直径=圆环扫掠截面直径，Sweep扫掠
        # ======================================================================
        圆环管截面2d = translate(圆环管路径半径, 0) * scale(圆环管截面半径, 圆环管截面半径) * Section(Arc(2.0 * math.pi))
        圆环管截面3d = rotate(Vec3(1, 0, 0), -0.5 * math.pi) * 圆环管截面2d
        圆环管路径 = Line(Arc(2.0 * math.pi))
        圆环管 = translate(0, 0, 圆环管圆心Z) * Sweep(圆环管截面3d, 圆环管路径)

        # ======================================================================
        # 步骤6：圆柱体6 — 临时坐标系原点(0,0,圆环管圆心Z)，直径=圆形线扫掠路径直径，沿Z+拉伸40
        # ======================================================================
        圆柱体6 = Cone(
            Vec3(0, 0, Z6),
            Vec3(0, 0, Z7),
            圆柱体6半径, 圆柱体6半径
        )

        # ======================================================================
        # 步骤7：底部圆柱体散热片 — 圆柱体6外侧，6个直径30圆柱，环形阵列，Z范围同圆柱体6
        # ======================================================================
        散热片半径 = 15.0
        散热片数量 = 6
        散热片列表 = []
        for i in range(散热片数量):
            angle = i * 2.0 * math.pi / 散热片数量
            cx = 圆柱体6半径 * math.cos(angle)
            cy = 圆柱体6半径 * math.sin(angle)
            散热片列表.append(Cone(
                Vec3(cx, cy, Z6),
                Vec3(cx, cy, Z7),
                散热片半径, 散热片半径
            ))
        底部散热片 = combine(*散热片列表)

        # ======================================================================
        # 步骤8：圆柱体8 — 临时坐标系原点(0,0,Z7)，直径=圆柱体6直径，沿Z+拉伸80
        # ======================================================================
        圆柱体8 = Cone(
            Vec3(0, 0, Z8),
            Vec3(0, 0, Z9),
            圆柱体8半径, 圆柱体8半径
        )

        # ======================================================================
        # 步骤9：圆柱体9和中部散热片 — 圆柱体6和底部散热片沿XOY面镜像（镜像面Z=圆柱体8拉伸中点）
        # ======================================================================
        圆柱体9 = translate(0, 0, 2.0 * 圆柱体8拉伸中点Z) * scale(1, 1, -1) * 圆柱体6
        中部散热片 = translate(0, 0, 2.0 * 圆柱体8拉伸中点Z) * scale(1, 1, -1) * 底部散热片

        # ======================================================================
        # 步骤10：圆柱体10 — 临时坐标系原点(0,0,Z7_mirror)，直径=圆柱体6直径，沿Z+拉伸(80+高度补偿)
        # ======================================================================
        圆柱体10 = Cone(
            Vec3(0, 0, Z10),
            Vec3(0, 0, Z11),
            圆柱体10半径, 圆柱体10半径
        )

        # ======================================================================
        # 步骤11：圆柱体11 — 圆柱体9沿XOY面镜像（镜像面Z=圆柱体10拉伸中点）
        # ======================================================================
        圆柱体11 = translate(0, 0, 2.0 * 圆柱体10拉伸中点Z) * scale(1, 1, -1) * 圆柱体9

        # ======================================================================
        # 步骤12：盖顶圆台1 — 临时坐标系原点(0,0,Z10_mirror)，底直径=圆柱体6直径-60，顶直径=120*缩放比，沿Z+拉伸85
        # ======================================================================
        盖顶圆台1 = Cone(
            Vec3(0, 0, Z12),
            Vec3(0, 0, Z13),
            盖顶圆台1底半径, 盖顶圆台1顶半径
        )

        # ======================================================================
        # 步骤13：耳环 — 临时坐标系原点(0,0,Z13)，YOZ面圆环，镜像出左右耳环
        # ======================================================================
        # 耳环圆心X = 0.5*盖顶圆台1顶直径 - 15
        # 耳环扫掠路径直径 = 30 - 耳环截面直径 = 30 - 5 = 25，路径半径 = 12.5
        # 耳环截面直径 = 5，截面半径 = 2.5

        耳环圆心X = 0.5 * 盖顶圆台1顶直径 - 15.0
        耳环圆心Z_temp = 0.5 * 30.0
        耳环路径半径 = 12.5
        耳环截面半径 = 2.5

        # 在XOY面创建耳环圆环，再旋转到YOZ面
        耳环截面2d = translate(耳环路径半径, 0) * scale(耳环截面半径, 耳环截面半径) * Section(Arc(2.0 * math.pi))
        耳环截面3d = rotate(Vec3(1, 0, 0), -0.5 * math.pi) * 耳环截面2d
        耳环路径 = Line(Arc(2.0 * math.pi))
        耳环圆环_xoy = Sweep(耳环截面3d, 耳环路径)

        # 旋转到YOZ面并定位
        右侧耳环 = translate(耳环圆心X, 0, Z13 + 耳环圆心Z_temp) * roty(math.pi / 2.0) * 耳环圆环_xoy
        左侧耳环 = scale(-1, 1, 1) * 右侧耳环

        # ======================================================================
        # 步骤14：圆柱体14 — 临时坐标系原点(0,0,圆环管圆心Z)，YOZ面，直径=圆环扫掠截面直径-20，沿X-拉伸
        # ======================================================================
        圆柱体14 = Cone(
            Vec3(0, 0, 圆环管圆心Z),
            Vec3(-圆柱体14拉伸距离, 0, 圆环管圆心Z),
            圆柱体14半径, 圆柱体14半径
        )

        # ======================================================================
        # 步骤15：圆柱体15 — 临时坐标系原点(-圆柱体14拉伸距离,0,圆环管圆心Z)，YOZ面，直径=圆柱体14直径+100，沿X-拉伸15
        # ======================================================================
        圆柱体15 = Cone(
            Vec3(-圆柱体14拉伸距离, 0, 圆环管圆心Z),
            Vec3(-圆柱体14拉伸距离 - 圆柱体15拉伸距离, 0, 圆环管圆心Z),
            圆柱体15半径, 圆柱体15半径
        )

        # ======================================================================
        # 步骤16：出水管圆环 — 临时坐标系原点(出水管弯头起点X,0,出水管弯头起点Z)，XOZ面1/4圆弧路径，截面直径=出水管直径
        # ======================================================================
        出水管扫掠路径半径 = 出水管扫掠路径直径 / 2.0

        # 1/4圆弧路径：从角度-pi/2到-pi（顺时针），圆心在(0,0,出水管扫掠路径半径)
        # 起点(-pi/2): (0, 0, 0)
        # 终点(-pi):   (-出水管扫掠路径半径, 0, 出水管扫掠路径半径)
        # 中点(-3pi/4): (-出水管扫掠路径半径*sqrt(2)/2, 0, 出水管扫掠路径半径*(1-sqrt(2)/2))
        出水管路径起点 = Vec3(0, 0, 0)
        出水管路径终点 = Vec3(-出水管扫掠路径半径, 0, 出水管扫掠路径半径)
        出水管路径中点 = Vec3(
            -出水管扫掠路径半径 * math.sqrt(2.0) / 2.0,
            0,
            出水管扫掠路径半径 * (1.0 - math.sqrt(2.0) / 2.0)
        )
        出水管路径弧 = Arc(出水管路径起点, 出水管路径中点, 出水管路径终点)
        出水管路径线 = Line(出水管路径弧)

        # 截面：圆形截面，法线对齐路径起点切线方向（+X方向）
        # 默认截面在XOY面（法线=Z），roty(-pi/2)使法线→+X，截面在YOZ面
        出水管截面 = roty(-math.pi / 2.0) * scale(出水管半径) * Section(Arc(2.0 * math.pi))
        出水管弯头 = translate(出水管弯头起点X, 0, 出水管弯头起点Z) * Sweep(出水管截面, 出水管路径线)

        # ======================================================================
        # 组合所有部件
        # ======================================================================
        self['QW型潜污泵'] = combine(
            底板,
            支撑圆台1,
            支撑圆台2,
            圆柱体4,
            圆环管,
            圆柱体6,
            底部散热片,
            圆柱体8,
            圆柱体9,
            中部散热片,
            圆柱体10,
            圆柱体11,
            盖顶圆台1,
            右侧耳环,
            左侧耳环,
            圆柱体14,
            圆柱体15,
            出水管弯头
        )


