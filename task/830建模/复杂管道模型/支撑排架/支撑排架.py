from pyp3d import *
import math


class 支撑排架(Component):
    def __init__(self):
        Component.__init__(self)

        # ============================== 基本参数 ==============================
        self['设备名称'] = Attr('支撑排架', obvious=True, readonly=False, group='专业属性')

        # 排架几何参数（排架矩形截面：长=X方向，宽=Y方向，形心位于全局原点）
        self['排架长度'] = Attr(500, obvious=True, group='几何属性')
        self['排架宽度'] = Attr(800, obvious=True, group='几何属性')
        self['排架高度'] = Attr(1000, obvious=True, group='几何属性')
        self['底部水平支撑柱高度'] = Attr(300, obvious=True, group='几何属性')

        # L型角钢截面参数（水平距离=X方向肢长，竖向高度=Y方向肢长，厚度=截面宽度）
        self['L型截面水平距离'] = Attr(40, obvious=True, group='几何属性')
        self['L型截面竖向高度'] = Attr(40, obvious=True, group='几何属性')
        self['L型截面厚度'] = Attr(10, obvious=True, group='几何属性')
        self['L型截面倒角半径'] = Attr(8, obvious=True, group='几何属性')

        # 支撑间距参数
        self['底部水平支撑柱间距'] = Attr(200, obvious=True, group='几何属性')
        self['竖向支撑柱间距'] = Attr(500, obvious=True, group='几何属性')
        self['水平支撑柱Z间距'] = Attr(300, obvious=True, group='几何属性')

        # 箱体参数
        self['箱体长度'] = Attr(150, obvious=True, group='几何属性')
        self['箱体宽度'] = Attr(150, obvious=True, group='几何属性')
        self['箱体高度'] = Attr(300, obvious=True, group='几何属性')

        self['模型'] = Attr(None, show=True)
        self.replace()

    @export
    def replace(self):
        # ============================== 读取参数 ==============================
        L    = self['排架长度']             # 排架矩形长度（X方向）
        W    = self['排架宽度']             # 排架矩形宽度（Y方向）
        H    = self['排架高度']             # 排架高度（Z方向）
        Hb   = self['底部水平支撑柱高度']     # 底部水平支撑柱所在高度
        hL   = self['L型截面水平距离']       # L型截面水平肢长度
        vL   = self['L型截面竖向高度']       # L型截面竖向肢高度
        tL   = self['L型截面厚度']          # L型截面厚度（截面宽度）
        rL   = self['L型截面倒角半径']       # L型截面内拐角倒角半径
        底部水平间距 = self['底部水平支撑柱间距']
        竖向柱间距   = self['竖向支撑柱间距']
        水平柱Z间距  = self['水平支撑柱Z间距']
        箱体长 = self['箱体长度']
        箱体宽 = self['箱体宽度']
        箱体高 = self['箱体高度']

        # ============================== 参数校验 ==============================
        if L <= 0 or W <= 0 or H <= 0:
            print('参数错误：排架长度、宽度、高度必须大于0')
            return
        if Hb <= 0 or Hb >= H:
            print('参数错误：底部水平支撑柱高度必须大于0且小于排架高度')
            return
        if hL <= 0 or vL <= 0 or tL <= 0:
            print('参数错误：L型截面水平距离、竖向高度、厚度必须大于0')
            return
        if rL < 0 or tL + rL >= hL or tL + rL >= vL:
            print('参数错误：L型截面倒角半径不能为负，且厚度+倒角半径必须小于水平距离与竖向高度')
            return
        if 箱体长 <= 0 or 箱体宽 <= 0 or 箱体高 <= 0:
            print('参数错误：箱体长度、宽度、高度必须大于0')
            return

        # ============================== 第0步：L型角钢截面 ==============================
        # 截面位于xoy面，外侧拐点(0,0)，水平肢沿+X(长hL)，竖向肢沿+Y(高vL)，厚度tL
        # 内拐角(tL,tL)处做半径rL的内圆角倒角（保留参考代码钢结构构件的倒角设计）
        if rL > 0:
            lineL = Line(
                Vec2(0, 0), Vec2(hL, 0), Vec2(hL, tL), Vec2(tL + rL, tL),
                translate(tL + rL, tL + rL) * rotz(-pi/2) * scale(rL) * Arc(-pi/2),
                Vec2(tL, tL + rL), Vec2(tL, vL), Vec2(0, vL), Vec2(0, 0)
            )
        else:
            lineL = Line(
                Vec2(0, 0), Vec2(hL, 0), Vec2(hL, tL), Vec2(tL, tL),
                Vec2(tL, vL), Vec2(0, vL), Vec2(0, 0)
            )
        sectionL = Section(lineL)

        # ============================== 第0.5步：翻转后的L型角钢截面（仅水平支撑柱使用） ==============================
        # 经用户确认，将原始L型截面绕通过中心的水平轴(X方向)翻转180°（截面1→截面2，y→vL−y）
        # 原"水平距离"肢(底部水平板)翻转到顶部(y∈[vL−tL,vL])，竖向肢保持在左侧(x∈[0,tL])
        # 保持逆时针绕向与原始截面一致；仅用于水平支撑柱，竖向支撑柱仍用原始sectionL
        if rL > 0:
            lineL2 = Line(
                Vec2(0, 0), Vec2(tL, 0), Vec2(tL, vL - tL - rL),
                translate(tL + rL, vL - tL - rL) * rotz(pi) * scale(rL) * Arc(-pi/2),
                Vec2(tL + rL, vL - tL), Vec2(hL, vL - tL), Vec2(hL, vL), Vec2(0, vL), Vec2(0, 0)
            )
        else:
            lineL2 = Line(
                Vec2(0, 0), Vec2(tL, 0), Vec2(tL, vL - tL),
                Vec2(hL, vL - tL), Vec2(hL, vL), Vec2(0, vL), Vec2(0, 0)
            )
        sectionL2 = Section(lineL2)

        # ============================== 第1步：竖向支撑柱（4根） ==============================
        # L型截面(xoy面，法线+Z)沿+Z拉伸(排架高度)，截面拐点与排架矩形四角点重合
        # 四角点截面绕Z旋转不同角度，使L型凹角开口朝排架内部
        vline = Line(Vec3(0, 0, 0), Vec3(0, 0, H))
        竖向柱后左 = trans(-L/2, -W/2, 0) * Sweep(sectionL, vline)
        竖向柱前左 = trans(L/2, -W/2, 0) * rotz(pi/2) * Sweep(sectionL, vline)
        竖向柱前右 = trans(L/2, W/2, 0) * rotz(pi) * Sweep(sectionL, vline)
        竖向柱后右 = trans(-L/2, W/2, 0) * rotz(-pi/2) * Sweep(sectionL, vline)

        # ============================== 第2步：底部水平支撑柱（4根） ==============================
        # 在z=底部水平支撑柱高度平面，翻转后的L型截面(sectionL2)沿排架矩形四边扫掠
        # 扫掠姿态（经用户确认）：恢复原始扫掠变换(rotx等)，翻转截面使"水平距离"肢(60mm)
        # 平铺在顶面(+Z高处)、原"竖向高度"肢(80mm)竖直朝上(+Z)、L拐点仍位于外轮廓线(矩形边线)上
        底部水平柱后 = Sweep(trans(-L/2, W/2, Hb) * rotx(pi/2) * sectionL2,
                             Line(Vec3(-L/2, W/2, Hb), Vec3(-L/2, -W/2, Hb)))
        底部水平柱前 = Sweep(trans(L/2, W/2, Hb) * rotx(-pi/2) * rotz(pi) * sectionL2,
                             Line(Vec3(L/2, W/2, Hb), Vec3(L/2, -W/2, Hb)))
        底部水平柱右 = Sweep(trans(L/2, W/2, Hb) * roty(-pi/2) * rotz(-pi/2) * sectionL2,
                             Line(Vec3(L/2, W/2, Hb), Vec3(-L/2, W/2, Hb)))
        底部水平柱左 = Sweep(trans(-L/2, -W/2, Hb) * roty(pi/2) * rotz(pi/2) * sectionL2,
                             Line(Vec3(-L/2, -W/2, Hb), Vec3(L/2, -W/2, Hb)))

        # ============================== 第3步：顶部水平支撑柱（4根） ==============================
        # 底部四根水平支撑柱沿+Z平移(排架高度-底部水平支撑柱高度)，复制得到顶部水平支撑柱
        顶部水平柱后 = trans(0, 0, H - Hb - vL) * 底部水平柱后
        顶部水平柱前 = trans(0, 0, H - Hb - vL) * 底部水平柱前
        顶部水平柱右 = trans(0, 0, H - Hb - vL) * 底部水平柱右
        顶部水平柱左 = trans(0, 0, H - Hb - vL) * 底部水平柱左

        # ============================== 第4步：箱体长度支撑柱 ==============================
        # 顶部后边水平支撑柱沿+X平移(箱体长度)，得到箱体长度支撑柱
        箱体长度支撑柱 = trans(箱体长, 0, 0) * 顶部水平柱后

        # ============================== 第5步：箱体宽度支撑柱 ==============================
        # 顶部右边水平支撑柱沿-Y平移(箱体宽度)，得到箱体宽度支撑柱
        箱体宽度支撑柱 = trans(0, -箱体宽, 0) * 顶部水平柱右

        # ============================== 第6步：底部水平支撑柱 ==============================
        # 底部右边水平支撑柱沿-Y平移(底部水平支撑柱间距)，得到第5根底部水平支撑柱
        底部水平支撑柱 = trans(0, -底部水平间距, 0) * 底部水平柱右

        # ============================== 第7步：竖向间距支撑柱 ==============================
        # 后右竖向支撑柱沿-Y平移(竖向支撑柱间距)复制，得到竖向间距支撑柱
        # 注：经用户确认，修改复制的基础模型部件（后左→后右），平移方向改为沿-Y
        # 默认参数下：后右柱Y=W/2=400 沿-Y平移300 → Y=100
        竖向间距支撑柱 = trans(0, -竖向柱间距, 0) * 竖向柱后右

        # ============================== 第8步：水平间距支撑柱 ==============================
        # 顶部后边水平支撑柱沿-Z平移(水平支撑柱Z间距)，得到水平间距支撑柱
        水平间距支撑柱 = trans(0, 0, -水平柱Z间距) * 顶部水平柱后

        # ============================== 第9步：箱体 ==============================
        # 临时坐标系原点=后右竖向柱顶部外角(-L/2, W/2, H)，以该点为箱体矩形截面角点
        # 箱体截面(长X=箱体长度)向+X延伸、(宽Y=箱体宽度)向-Y延伸，沿+Z拉伸(箱体高度)，得到长方体箱体
        # 注：经用户确认，箱体向+X、-Y延伸（完全位于排架内部，Y∈[W/2-箱体宽, W/2]）
        箱体 = trans(-L/2 + hL/2, W/2 - 箱体宽 - hL/2, H) * scale(箱体长, 箱体宽, 箱体高) * Box()

        # ============================== 布尔相加全部构件并平移至插入点 ==============================
        # 插入点=竖向支撑柱的前面左上角点=(L/2,-W/2,H)，整体平移使插入点落到全局原点(0,0,0)
        self['模型'] = trans(-L/2, W/2, -H) * (
            竖向柱后左 + 竖向柱前左 + 竖向柱前右 + 竖向柱后右
            + 底部水平柱后 + 底部水平柱前 + 底部水平柱右 + 底部水平柱左
            + 顶部水平柱后 + 顶部水平柱前 + 顶部水平柱右 + 顶部水平柱左
            + 箱体长度支撑柱 + 箱体宽度支撑柱 + 底部水平支撑柱
            + 竖向间距支撑柱 + 水平间距支撑柱 + 箱体
        )


if __name__ == "__main__":
    FinalGeometry = 支撑排架()
    place(FinalGeometry)
